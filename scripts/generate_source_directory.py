def load_collections(catalog_dir: Path) -> tuple[dict, dict]:
    collections = {}
    for channel in ("all", "general"):
        collection = parse_json((catalog_dir / f"{channel}.json").read_bytes(), MAX_MANIFEST)
        validate_collection(collection, channel, upstream=False)
        collections[channel] = collection
    all_collection, general = collections["all"], collections["general"]
    require((all_collection["releaseId"], all_collection["catalogSequence"]) ==
            (general["releaseId"], general["catalogSequence"]), "directory collection versions differ")
    require(general["rules"] == [rule for rule in all_collection["rules"] if rule["contentRating"] != "adult"],
            "directory general collection is not the exact non-adult subset")
    return all_collection, general


def markdown_text(value: str) -> str:
    # Names are external metadata, not Markdown or HTML supplied by maintainers.
    text = html.escape(" ".join(value.split()), quote=False)
    return re.sub(r"([\\`*_\[\]{}()!|#~])", r"\\\1", text)


def relative_link(current: Path, target: Path) -> str:
    return posixpath.relpath(target.as_posix(), current.parent.as_posix())


def language_switch(language: str, channel: str) -> str:
    current = DOCUMENT_PATHS[language][channel]
    links = []
    for code, label in LANGUAGE_NAMES.items():
        target = relative_link(current, DOCUMENT_PATHS[code][channel])
        links.append(f"**{label}**" if code == language else f"[{label}]({target})")
    return " | ".join(links)


def source_table(rules: list[dict], language: str = "en") -> list[str]:
    text = TEXT[language]
    if not rules:
        return [text["empty"]]
    rows = [
        text["columns"],
        "| --- | --- | --- | --- | --- |",
    ]
    for rule in sorted(rules, key=lambda item: (item["name"].casefold(), item["id"])):
        rule_id = rule["id"]
        stable_url = f"{RELEASE_BASE}/latest/download/{rule_id}.kyyrule"
        rows.append(
            f"| {markdown_text(rule['name'])} | `{rule_id}` | {text['ratings'][rule['contentRating']]} "
            f"| [{text['import_label']}]({stable_url}) | [{text['download_label']}]({rule['url']}) |"
        )
    return rows


def render_directory(collection: dict, rules: list[dict], adult: bool, other_count: int,
                     language: str = "en") -> str:
    text = TEXT[language]
    channel = "adult" if adult else "general"
    current = DOCUMENT_PATHS[language][channel]
    navigation = text[f"{channel}_navigation"].format(
        **{name: relative_link(current, path) for name, path in DOCUMENT_PATHS[language].items()})
    lines = [
        GENERATED_NOTICE,
        "",
        f"# {text[f'{channel}_title']}",
        "",
        language_switch(language, channel),
        "",
        navigation,
        "",
        text[f"{channel}_notice"],
        "",
        text[f"{channel}_count"].format(count=len(rules), other_count=other_count),
        text["snapshot"].format(release=collection["releaseId"], sequence=collection["catalogSequence"]),
        "",
        f"## {text['instructions_title']}",
        "",
        *text["instructions"],
        "",
        f"## {text['sources_title']}",
        "",
        *source_table(rules, language),
        "",
        f"## {text['notes_title']}",
        "",
        text["download_note"],
        "",
        *text["notes"],
        "",
        *text["footer"],
        "",
    ]
    return "\n".join(lines)


def generate_documents(catalog_dir: Path) -> dict[Path, str]:
    all_collection, general = load_collections(catalog_dir)
    adult_rules = [rule for rule in all_collection["rules"] if rule["contentRating"] == "adult"]
    documents = {}
    for language, paths in DOCUMENT_PATHS.items():
        documents[paths["general"]] = render_directory(
            general, general["rules"], adult=False, other_count=len(adult_rules), language=language)
        documents[paths["adult"]] = render_directory(
            all_collection, adult_rules, adult=True, other_count=general["count"], language=language)
    return documents


def generate(catalog_dir: Path, output_dir: Path, check: bool = False) -> bool:
    documents = generate_documents(catalog_dir)
    stale = []
    for relative, text in documents.items():
        path = output_dir / relative
        expected = text.encode("utf-8")
        if check:
            if not path.is_file() or path.read_bytes() != expected:
                stale.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    if stale:
        print("Source directories are missing or stale: " + ", ".join(stale))
        print("Run: python3 scripts/generate_source_directory.py")
        return False
    print("Source directories are current." if check else "Generated " + ", ".join(map(str, documents)) + ".")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog-dir", type=Path, default=ROOT, help="directory containing all.json and general.json")
    parser.add_argument("--output-dir", type=Path, default=ROOT, help="repository or preview directory")
    parser.add_argument("--check", action="store_true", help="fail on missing or stale directories without writing")
    options = parser.parse_args()
    if not generate(options.catalog_dir, options.output_dir, options.check):
        raise SystemExit(1)


if __name__ == "__main__":
    try:
        main()
    except (MirrorError, OSError) as error:
        raise SystemExit(str(error))
