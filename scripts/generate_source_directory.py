#!/usr/bin/env python3
"""Generate user-facing Markdown directories from published mirror metadata only."""
from __future__ import annotations

import argparse
import html
import re
from pathlib import Path

from mirror_release import MAX_MANIFEST, REPOSITORY, MirrorError, parse_json, require, validate_collection

ROOT = Path(__file__).resolve().parents[1]
GENERAL_PATH = Path("SOURCES.md")
ADULT_PATH = Path("docs/SOURCES_ADULT.md")
RELEASE_BASE = f"https://github.com/{REPOSITORY}/releases"
GENERATED_NOTICE = "<!-- Generated by scripts/generate_source_directory.py. Do not edit by hand. -->"
RATINGS = {
    "safe": "普通（safe）",
    "teen": "青少年（teen）",
    "mature": "成熟内容（mature）",
    "adult": "成人（adult）",
}


def load_collections(catalog_dir: Path) -> tuple[dict, dict]:
    collections = {}
    for channel in ("all", "general"):
        collection = parse_json((catalog_dir / f"{channel}.json").read_bytes(), MAX_MANIFEST)
        validate_collection(collection, channel, upstream=False)
        collections[channel] = collection
    all_collection, general = collections["all"], collections["general"]
    require((all_collection["releaseId"], all_collection["catalogSequence"]) ==
            (general["releaseId"], general["catalogSequence"]), "directory collection versions differ")
    require(general["rules"] == [rule for rule in all_collection["rules"] if rule["contentRating"] != "adult"],
            "directory general collection is not the exact non-adult subset")
    return all_collection, general


def markdown_text(value: str) -> str:
    # Names are external metadata, not Markdown or HTML supplied by maintainers.
    text = html.escape(" ".join(value.split()), quote=False)
    return re.sub(r"([\\`*_\[\]{}()!|#~])", r"\\\1", text)


def source_table(rules: list[dict]) -> list[str]:
    if not rules:
        return ["当前没有此分组的已发布来源。"]
    rows = [
        "| 来源名称 | 规则 ID | 内容分级 | 单源导入地址 | 固定版本 |",
        "| --- | --- | --- | --- | --- |",
    ]
    for rule in sorted(rules, key=lambda item: (item["name"].casefold(), item["id"])):
        rule_id = rule["id"]
        stable_url = f"{RELEASE_BASE}/latest/download/{rule_id}.kyyrule"
        rows.append(
            f"| {markdown_text(rule['name'])} | `{rule_id}` | {RATINGS[rule['contentRating']]} "
            f"| [导入链接]({stable_url}) | [下载该版本]({rule['url']}) |"
        )
    return rows


def render_directory(collection: dict, rules: list[dict], adult: bool, other_count: int) -> str:
    title = "成人来源目录" if adult else "单源规则目录"
    navigation = ("[返回常规目录](../SOURCES.md) · [返回 README](../README.md)" if adult else
                  "[返回 README](README.md) · [成人来源单独目录](docs/SOURCES_ADULT.md)")
    notice = ("**本页仅列出成人来源。使用者需符合适用年龄及法律要求；不希望查看时请返回常规目录。**" if adult else
              "**本页不含成人来源，但包含 mature（成熟内容）分级，不代表所有来源均适合所有年龄。**")
    count = (f"本页共 {len(rules)} 个成人来源；另有 {other_count} 个常规来源。" if adult else
             f"本页共 {len(rules)} 个常规来源；另有 {other_count} 个成人来源，列于单独目录。")
    lines = [
        GENERATED_NOTICE,
        "",
        f"# {title}",
        "",
        navigation,
        "",
        notice,
        "",
        count,
        f"目录快照：`{collection['releaseId']}` · 序号：`{collection['catalogSequence']}`。",
        "",
        "## 查找与单独导入",
        "",
        "1. 使用浏览器的“在页面中查找”（电脑上按 `Ctrl+F` / `Cmd+F`），搜索来源名称或规则 ID。",
        "2. 对所需来源的“导入链接”右键或长按，选择“复制链接地址”；不要复制当前目录页地址。",
        "3. 在兼容阅读器的远程规则导入入口粘贴地址，检查名称、域名和权限等导入预览后自行确认。",
        "",
        "## 来源列表",
        "",
        *source_table(rules),
        "",
        "## 链接说明",
        "",
        "点击链接可能直接下载 `.kyyrule` 文件，不代表能一键唤起 App 安装。也可以使用“下载该版本”获取固定版本文件后手动导入。",
        "",
        "- “导入链接”指向最新 Release 中同一规则 ID 的包，方便保存或分享；不代表安装后会自动更新。",
        "- “下载该版本”绑定本页目录快照；集合清单仍使用固定版本 URL、大小及 SHA-256，不使用 `latest` 做完整性校验。",
        "- 来源从最新版本移除后，其稳定导入链接可能失效；不要将历史包视为仍受维护或当前可用的来源。",
        "- 名称和分级沿用公开发布清单，不代表站点可用性、内容授权或任何 App 的审核、推荐与保证。",
        "",
        "本目录仅提供社区维护的可选加密规则包链接，不托管漫画或视频内容，也不包含规则明文或密钥。",
        "目录由已发布的集合清单自动生成；反馈或移除请求请使用仓库 Issues，并提供规则 ID。",
        "",
    ]
    return "\n".join(lines)


def generate_documents(catalog_dir: Path) -> dict[Path, str]:
    all_collection, general = load_collections(catalog_dir)
    adult_rules = [rule for rule in all_collection["rules"] if rule["contentRating"] == "adult"]
    return {
        GENERAL_PATH: render_directory(general, general["rules"], adult=False, other_count=len(adult_rules)),
        ADULT_PATH: render_directory(all_collection, adult_rules, adult=True, other_count=general["count"]),
    }


def generate(catalog_dir: Path, output_dir: Path, check: bool = False) -> bool:
    documents = generate_documents(catalog_dir)
    stale = []
    for relative, text in documents.items():
        path = output_dir / relative
        expected = text.encode("utf-8")
        if check:
            if not path.is_file() or path.read_bytes() != expected:
                stale.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    if stale:
        print("Source directories are missing or stale: " + ", ".join(stale))
        print("Run: python3 scripts/generate_source_directory.py")
        return False
    print("Source directories are current." if check else "Generated SOURCES.md and docs/SOURCES_ADULT.md.")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog-dir", type=Path, default=ROOT, help="directory containing all.json and general.json")
    parser.add_argument("--output-dir", type=Path, default=ROOT, help="repository or preview directory")
    parser.add_argument("--check", action="store_true", help="fail on missing or stale directories without writing")
    options = parser.parse_args()
    if not generate(options.catalog_dir, options.output_dir, options.check):
        raise SystemExit(1)


if __name__ == "__main__":
    try:
        main()
    except (MirrorError, OSError) as error:
        raise SystemExit(str(error))
